// Ejercicio 2. Ampliar y reducir una lista
// Datos de partida del enunciado; la solución queda pendiente.

let productos = ["Ratón", "Teclado", "Monitor"];

// Añadimos "Impresora" al final de la lista
productos.push("Impresora");
console.log(productos);

// Añadimos Altavoces al principio
productos.unshift("Altavoces");
console.log(productos);

// Eliminamos el último producto
productos.pop();
console.log(productos);

// Eliminamos el primer producto
productos.shift();
console.log(productos);
